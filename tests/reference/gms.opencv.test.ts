import { describe, it, expect } from "vitest";
import jsfeatNext from "../../src/jsfeatNext";
import type { match_t } from "../../src/bfmatcher/match_t";
import { loadFixture } from "../fixtures/opencv/loader";

/**
 * `gms.filter` against `cv::xfeatures2d::matchGMS` (#134).
 *
 * GMS has no jsfeat counterpart, so the vendored-oracle parity suite has
 * nothing to say about it; these fixtures are its ground truth. Each one is
 * pure geometry: the keypoint positions of two views of the committed scene,
 * the image sizes, ORB + brute-force matches with a known share of corrupted
 * train indices, and the indices of the matches OpenCV kept. The port must
 * reproduce that kept set exactly, which pins its float/double grid arithmetic
 * and its tie-breaking. Generated by `scripts/gen-opencv-fixtures.py --only gms`;
 * see "GMS fixtures" in `tests/fixtures/opencv/README.md`.
 *
 * Two kinds of fixture are the exception to "two views of the scene". The
 * `gms-synth-*` ones (`--only gms-synthetic`) are 800 random points under an
 * exact transform, one per search path: the ORB fixtures keep only 6-8
 * matches on the rotation and scale paths, which pins those searches weakly,
 * and these keep hundreds. `gms-boundaries` is hand-placed on OpenCV's
 * decision boundaries (cell borders, ties, a score equal to the threshold),
 * which no other fixture lands on.
 */

/** One ORB and one synthetic fixture per branch of OpenCV's `getInlierMask`. */
const PATHS = [
    "gms-default",
    "gms-rotation",
    "gms-scale",
    "gms-rotation-scale",
    "gms-synth-default",
    "gms-synth-rotation",
    "gms-synth-scale",
    "gms-synth-rotation-scale",
];

interface GmsPayload {
    size1: [number, number]; // [width, height]
    size2: [number, number];
    with_rotation: boolean;
    with_scale: boolean;
    threshold_factor: number;
    keypoints1: [number, number][]; // KeyPoint.pt, float32-exact
    keypoints2: [number, number][];
    matches: [number, number, number][]; // [queryIdx, trainIdx, distance]
    kept: number[]; // indices into `matches` of matchGMS's output, ascending
}

const toKp = (pts: [number, number][]) => pts.map(([x, y]) => new jsfeatNext.keypoint_t(x, y));
const toMatches = (ms: [number, number, number][]) => ms.map(([q, t, d]) => new jsfeatNext.match_t(q, t, d));
const run = (p: GmsPayload, matches: match_t[]) =>
    jsfeatNext.gms.filter(
        { width: p.size1[0], height: p.size1[1] },
        { width: p.size2[0], height: p.size2[1] },
        toKp(p.keypoints1),
        toKp(p.keypoints2),
        matches,
        p.with_rotation,
        p.with_scale,
        p.threshold_factor
    );

describe("gms.filter vs cv::xfeatures2d::matchGMS (OpenCV fixtures)", () => {
    it("fixture flags match the file name", () => {
        // A fixture generated with the wrong flags would pin the wrong path
        // and still pass. The name says which path: "rotation" and "scale".
        for (const name of [...PATHS, "gms-boundaries"]) {
            const { payload: p } = loadFixture<GmsPayload>(name);
            expect({ name, with_rotation: p.with_rotation, with_scale: p.with_scale }).toEqual({
                name,
                with_rotation: name.includes("rotation"),
                with_scale: name.includes("scale"),
            });
        }
    });

    it.each(PATHS)("%s: kept matches are bit-exact", (name) => {
        const { payload: p } = loadFixture<GmsPayload>(name);
        const matches = toMatches(p.matches);
        const out = run(p, matches);
        expect(out.map((m) => matches.indexOf(m))).toEqual(p.kept);
    });

    it("gms-boundaries: cell borders, ties and the threshold are bit-exact", () => {
        // The ORB fixtures barely constrain three details: float vs double
        // grid arithmetic, how a tie between two right cells is broken, and
        // whether a score equal to the threshold is kept (only gms-scale
        // notices the last). These hand-placed groups flip under each wrong
        // reading. See gms_boundaries() in the generator.
        const { payload: p } = loadFixture<GmsPayload>("gms-boundaries");
        const matches = toMatches(p.matches);
        const out = run(p, matches);
        expect(out.map((m) => matches.indexOf(m))).toEqual(p.kept);
    });
});

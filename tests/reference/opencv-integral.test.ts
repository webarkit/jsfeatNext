import { afterEach, beforeEach, describe, it, expect } from "vitest";
import { createHash } from "node:crypto";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import jsfeatNext from "../../src/jsfeatNext";
import { U8C1 } from "../properties/helpers";
import { FIXTURE_DIR, loadFixture, loadScene } from "../fixtures/opencv/loader";

/**
 * `compute_integral_image` against OpenCV (#132).
 *
 * The first fixture of the OpenCV ground-truth harness, chosen because it
 * validates the harness itself: the integral image is pure integer arithmetic
 * that must match bit-for-bit, so a mismatch indicts the harness (image dump,
 * encoding, loader) rather than the algorithm under test. Only after this is
 * green can a GMS fixture (#134) be trusted.
 *
 * It is also a genuine cross-check of a shipped function against a third-party
 * implementation, which the vendored-jsfeat parity suite cannot give: jsfeat and
 * jsfeatNext share the algorithm, so a defect present in both (like the
 * uninitialised first column fixed in #131) is invisible to it.
 *
 * The fixture is generated by `scripts/gen-opencv-fixtures.py --only integral`
 * from `cv2.integral2`. The tilted sum is out of scope: no consumer needs it.
 */

interface IntegralPayload {
    width: number;
    height: number;
    sum_sha256: string;
    sqsum_sha256: string;
    sum_first_row: number[];
    sum_first_col: number[];
}

const sha256 = (b: Uint8Array) => createHash("sha256").update(b).digest("hex");

describe("compute_integral_image vs cv2.integral / cv2.integral2 (OpenCV fixture)", () => {
    it("sum is bit-exact, first column included, on a dirty destination", () => {
        const { meta, payload } = loadFixture<IntegralPayload>("integral-scene");
        const scene = loadScene();
        expect(scene.width).toBe(payload.width);
        expect(scene.height).toBe(payload.height);

        const img = new jsfeatNext.matrix_t(scene.width, scene.height, U8C1);
        img.data.set(scene.data);
        const stride = scene.width + 1;
        const n = stride * (scene.height + 1);
        const sum = new Int32Array(n).fill(999); // sentinel: #131's failure mode
        const sq = new Float64Array(n).fill(999);
        jsfeatNext.imgproc.compute_integral_image(img, sum as never, sq as never, null as never);

        expect(sha256(new Uint8Array(sum.buffer))).toBe(payload.sum_sha256);
        expect(sha256(new Uint8Array(sq.buffer))).toBe(payload.sqsum_sha256);
        expect(Array.from(sum.subarray(0, stride))).toEqual(payload.sum_first_row);
        expect(Array.from({ length: scene.height + 1 }, (_, y) => sum[y * stride])).toEqual(payload.sum_first_col);
        expect(meta.opencv_version).toMatch(/^4\./);
    });

    describe("fixture integrity", () => {
        let tmpDir: string;

        beforeEach(() => {
            // a throwaway copy of the fixture, so the tamper cases never touch the committed files
            tmpDir = mkdtempSync(join(tmpdir(), "jsfeat-opencv-fixture-"));
            copyFileSync(join(FIXTURE_DIR, "scene-640x480.pgm"), join(tmpDir, "scene-640x480.pgm"));
            copyFileSync(join(FIXTURE_DIR, "integral-scene.json"), join(tmpDir, "integral-scene.json"));
        });

        afterEach(() => {
            rmSync(tmpDir, { recursive: true, force: true });
        });

        it("accepts an untouched copy (so the tamper cases below fail for the right reason)", () => {
            expect(() => loadFixture("integral-scene", tmpDir)).not.toThrow();
        });

        it("rejects a fixture whose sha256 does not match its image", () => {
            const file = join(tmpDir, "integral-scene.json");
            const json = JSON.parse(readFileSync(file, "utf8"));
            json.meta.sha256 = json.meta.sha256.replace(/^./, (c: string) => (c === "0" ? "1" : "0"));
            writeFileSync(file, JSON.stringify(json));
            expect(() => loadFixture("integral-scene", tmpDir)).toThrow(/sha256/);
        });

        it("rejects an image whose bytes changed under an unchanged fixture", () => {
            const file = join(tmpDir, "scene-640x480.pgm");
            const bytes = readFileSync(file);
            bytes[bytes.length - 1] ^= 0xff;
            writeFileSync(file, bytes);
            expect(() => loadFixture("integral-scene", tmpDir)).toThrow(/sha256/);
        });
    });
});

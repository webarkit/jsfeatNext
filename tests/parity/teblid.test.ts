import { describe, it, expect } from "vitest";
import jsfeatNext from "../../src/jsfeatNext";
import { matrix_t } from "../../src/matrix_t/matrix_t";
import { keypoint_t } from "../../src/keypoint_t/keypoint_t";
import { teblid } from "../../src/teblid/teblid";
import { loadFixture, loadScene } from "../fixtures/opencv/loader";

/**
 * `teblid.describe` against `cv::xfeatures2d::TEBLID::compute` of OpenCV
 * 4.10.0 (#135).
 *
 * jsfeat has no TEBLID, so the fixtures are the ground truth: a fixed,
 * seeded keypoint list per case (interior, each border inside / at / beyond
 * the 1.75x margin, corners, ORB-like and large sizes, angles), described by
 * OpenCV at both widths and at scale factors 1 and 5. Generated by
 * `scripts/gen-opencv-fixtures.py --only teblid`. Bit-exact: every byte of
 * every row of every case must equal OpenCV's, with no tolerance.
 */

interface TeblidCase {
    name: string;
    image: "scene" | "tiny";
    scale_factor: number;
    keypoints: [number, number, number, number][]; // x, y, size, angle in degrees (float32-exact)
    descriptors: string[]; // one hex string per row
}

interface TeblidPayload {
    cases: TeblidCase[];
}

/** OpenCV's `CV_DEGREES_TO_RADS`. */
const DEG2RAD = 0.017453292519943295;

const scene = loadScene();

/** The scene, or its top-left 24x24 crop, as a U8C1 matrix. */
function image(kind: "scene" | "tiny"): matrix_t {
    const w = kind === "scene" ? scene.width : 24;
    const h = kind === "scene" ? scene.height : 24;
    const m = new matrix_t(w, h, jsfeatNext.U8C1_t);
    for (let y = 0; y < h; ++y) {
        for (let x = 0; x < w; ++x) m.data[y * w + x] = scene.data[y * scene.width + x];
    }
    return m;
}

const images = { scene: image("scene"), tiny: image("tiny") };

const hex = (d: matrix_t, row: number, bytes: number): string => {
    let s = "";
    for (let i = 0; i < bytes; ++i) s += d.data[row * bytes + i].toString(16).padStart(2, "0");
    return s;
};

const engine = new teblid();

for (const bits of [256, 512] as const) {
    describe(`teblid p${bits} vs OpenCV 4.10.0`, () => {
        const fixture = loadFixture<TeblidPayload>(`teblid-p${bits}`);

        it("covers both scale factors and both images", () => {
            const { cases } = fixture.payload;
            expect(cases.some((c) => c.scale_factor === 1)).toBe(true);
            expect(cases.some((c) => c.scale_factor === 5)).toBe(true);
            expect(cases.some((c) => c.image === "tiny")).toBe(true);
        });

        for (const c of fixture.payload.cases) {
            it(`${c.name} (scale_factor ${c.scale_factor})`, () => {
                const kps = c.keypoints.map(
                    ([x, y, size, deg]) =>
                        new keypoint_t(x, y, 0, 0, deg === -1 ? -1 : Math.fround(deg) * DEG2RAD, size)
                );
                expect(c.descriptors.length).toBe(kps.length);
                const out = new matrix_t(bits / 8, 1, jsfeatNext.U8C1_t);
                engine.describe(images[c.image], kps, kps.length, out, { bits, scale_factor: c.scale_factor });
                expect(out.cols).toBe(bits / 8);
                expect(out.rows).toBe(kps.length);
                for (let i = 0; i < kps.length; ++i) {
                    const got = hex(out, i, bits / 8);
                    if (got !== c.descriptors[i]) {
                        expect.fail(
                            `${c.name} sf=${c.scale_factor}: keypoint ${i} ${JSON.stringify(c.keypoints[i])}\n` +
                                `  got      ${got}\n  expected ${c.descriptors[i]}`
                        );
                    }
                }
            });
        }
    });
}

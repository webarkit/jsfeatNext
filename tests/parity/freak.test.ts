import { describe, it, expect } from "vitest";
import jsfeatNext from "../../src/jsfeatNext";
import { matrix_t } from "../../src/matrix_t/matrix_t";
import { keypoint_t } from "../../src/keypoint_t/keypoint_t";
import { freak, freak_params, type FreakOptions } from "../../src/freak/freak";
import { loadFixture } from "../fixtures/opencv/loader";
import { freakImages, type FreakImageName, type FreakImageParams } from "../fixtures/opencv/freak_images";

/**
 * `freak.describe` against `cv2.xfeatures2d.FREAK_create(...).compute` of
 * OpenCV 4.10.0 (#80).
 *
 * jsfeat has no FREAK, so `freak.json` is the ground truth: a fixed keypoint
 * list per case (interior, each border inside / at / beyond the pattern size,
 * corners, every scale bin, flat patches, a textured image and its 90 degree
 * rotation). Generated by `scripts/gen-opencv-fixtures.py --only freak`.
 * Bit-exact: the kept keypoints (same objects, same order), every angle and
 * every byte of every row must equal OpenCV's, with no tolerance.
 */

interface FreakCase {
    name: string;
    image: FreakImageName;
    options: Required<FreakOptions>;
    keypoints: [number, number, number][]; // x, y, size (float32-exact)
    kept: number[]; // input indices, in OpenCV's output order
    angles_deg: number[]; // float32 degrees, one per kept keypoint
    descriptors: string[]; // one hex string per kept keypoint
}

interface FreakPayload {
    cases: FreakCase[];
}

/** OpenCV's `CV_DEGREES_TO_RADS`. */
const DEG2RAD = 0.017453292519943295;

const fixture = loadFixture<FreakPayload>("freak");
const params = fixture.meta.params as unknown as FreakImageParams & { pattern_sizes_default: number[] };
const images = freakImages(params);

const hex = (d: matrix_t, row: number): string => {
    let s = "";
    for (let i = 0; i < 64; ++i) s += d.data[row * 64 + i].toString(16).padStart(2, "0");
    return s;
};

const engine = new freak();

describe("freak vs OpenCV 4.10.0", () => {
    it("builds OpenCV's pattern sizes for the defaults", () => {
        expect(Array.from(freak_params(22, 4).sizes)).toEqual(params.pattern_sizes_default);
    });

    it("covers every image and every option", () => {
        const { cases } = fixture.payload;
        for (const img of ["scene", "scene_rot90", "flat", "texture", "texture_rot90"]) {
            expect(cases.some((c) => c.image === img)).toBe(true);
        }
        expect(cases.some((c) => !c.options.orientation_normalized)).toBe(true);
        expect(cases.some((c) => !c.options.scale_normalized)).toBe(true);
        expect(cases.some((c) => c.options.pattern_scale !== 22)).toBe(true);
        expect(cases.some((c) => c.options.n_octaves !== 4)).toBe(true);
    });

    for (const c of fixture.payload.cases) {
        it(c.name, () => {
            const originals = c.keypoints.map(([x, y, size]) => new keypoint_t(x, y, 0, 0, -1, size));
            const kps = originals.slice();
            const d = new matrix_t(64, 1, jsfeatNext.U8C1_t);
            const kept = engine.describe(images[c.image], kps, kps.length, d, c.options);

            expect(kept, `${c.name}: kept count`).toBe(c.kept.length);
            expect(d.cols).toBe(64);
            expect(d.rows).toBe(kept);
            for (let i = 0; i < kept; ++i) {
                if (kps[i] !== originals[c.kept[i]]) {
                    const at = originals.indexOf(kps[i]);
                    expect.fail(`${c.name}: row ${i} is input ${at}, expected input ${c.kept[i]}`);
                }
            }
            for (let i = 0; i < kept; ++i) {
                const want = Math.fround(c.angles_deg[i]) * DEG2RAD;
                if (kps[i].angle !== want) {
                    expect.fail(
                        `${c.name}: row ${i} (input ${c.kept[i]} ${JSON.stringify(c.keypoints[c.kept[i]])}) ` +
                            `angle ${kps[i].angle / DEG2RAD} deg, expected ${c.angles_deg[i]} deg`
                    );
                }
            }
            for (let i = 0; i < kept; ++i) {
                const got = hex(d, i);
                if (got !== c.descriptors[i]) {
                    expect.fail(
                        `${c.name}: row ${i} (input ${c.kept[i]} ${JSON.stringify(c.keypoints[c.kept[i]])})\n` +
                            `  got      ${got}\n  expected ${c.descriptors[i]}`
                    );
                }
            }
        });
    }
});
